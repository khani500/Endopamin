export const SELECTION_PREFERENCE_TIER_OVERRIDES = Object.freeze({
  beginner: BEGINNER_SELECTION_PREFERENCES,
});

export function selectionPreferenceKey(slotKind) {
  if (slotKind?.pattern === 'ACC') return 'ACC:' + slotKind.accessoryKind;
  if (slotKind?.pattern === 'CORE') return 'CORE';
  const intent = { structural_primary: 'P', structural_secondary: 'S' }[slotKind?.intent];
  return intent ? slotKind.pattern + '.' + intent : undefined;
}

export function selectionPreferenceList(slotKind, tier) {
  const key = selectionPreferenceKey(slotKind);
  return SELECTION_PREFERENCE_TIER_OVERRIDES[tier]?.[key] ?? SELECTION_PREFERENCES[key];
}

export function selectionPreferenceIndex(slotKind, tier, exerciseId) {
  const list = selectionPreferenceList(slotKind, tier);
  const index = list?.indexOf(exerciseId) ?? -1;
  return index < 0 ? (list?.length ?? 0) : index;
}

/** Diagnostic only: never reject an eligible ID because it has no authored preference. */
export function unlistedEligibleExerciseIds(slotKind, tier, candidates) {
  const list = selectionPreferenceList(slotKind, tier) ?? [];
  return [...new Set(candidates.map((c) => c.exerciseId).filter((id) => !list.includes(id)))].sort();
}
